// I18n Class
class I18n {
  constructor() {
    this.supportedLanguages = Object.keys(translations);
    this.currentLang = this.detectLanguage();
  }

  detectLanguage() {
    const saved = localStorage.getItem('selectedLanguage');
    if (saved && this.supportedLanguages.includes(saved)) {
      return saved;
    }
    const browserLang = (navigator.language || 'en').toLowerCase().split('-')[0];
    return this.supportedLanguages.includes(browserLang) ? browserLang : 'en';
  }

  t(key) {
    return translations[this.currentLang]?.[key] || translations.en?.[key] || key;
  }

  setLanguage(lang) {
    if (this.supportedLanguages.includes(lang)) {
      this.currentLang = lang;
      localStorage.setItem('selectedLanguage', lang);
      this.updateAllTranslations();
      return true;
    }
    return false;
  }

  updateAllTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
      const key = element.getAttribute('data-i18n');
      const translation = this.t(key);

      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        element.placeholder = translation;
      } else {
        element.textContent = translation;

        if (element.hasAttribute('data-text')) {
          element.setAttribute('data-text', translation);
        }
      }
    });
  }
}

// Global i18n instance
const i18n = new I18n();

document.addEventListener('DOMContentLoaded', () => {
  i18n.updateAllTranslations();
});